/// Port of the unit test `EqualWithSafeRelError` helper (float version).
fn equal_with_safe_rel_error(
    value: f32,
    expected: f32,
    eps: f32,
    min_expected: f32,
) -> (bool, f32) {
    if value == expected {
        return (true, 0.0);
    }
    if value.is_nan() && expected.is_nan() {
        return (true, 0.0);
    }
    let div = if expected > 0.0 {
        if expected < min_expected {
            min_expected
        } else {
            expected
        }
    } else if -expected < min_expected {
        min_expected
    } else {
        -expected
    };
    let err = (if value > expected {
        value - expected
    } else {
        expected - value
    }) / div;
    (err <= eps, err)
}

fn to_pixels(img: &[f32]) -> Vec<Pixel> {
    img.chunks_exact(4)
        .map(|c| [c[0], c[1], c[2], c[3]])
        .collect()
}

fn from_pixels(px: &[Pixel], img: &mut [f32]) {
    for (i, p) in px.iter().enumerate() {
        img[i * 4..i * 4 + 4].copy_from_slice(p);
    }
}

fn renderer(style: FixedFunctionOpStyle, params: &[f64]) -> FixedFunctionOp {
    FixedFunctionOp::new(FixedFunctionOpData::new(style, params).unwrap()).unwrap()
}

/// Apply the op to the first `num_samples` pixels of `img` (in place) and
/// compare with `expected`.
#[track_caller]
fn apply_fixed_function(
    img: &mut [f32],
    expected: &[f32],
    num_samples: usize,
    style: FixedFunctionOpStyle,
    params: &[f64],
    error_threshold: f32,
) {
    let op = renderer(style, params);
    let n = num_samples * 4;
    let mut px = to_pixels(&img[..n]);
    op.apply(&mut px);
    from_pixels(&px, &mut img[..n]);

    let mut failures = Vec::new();
    for idx in 0..n {
        let (ok, err) = equal_with_safe_rel_error(img[idx], expected[idx], error_threshold, 1.0);
        if !ok {
            failures.push(format!(
                "Index: {idx} - Values: {} expected: {} - Error: {err} ({:.3}x of Threshold: {error_threshold})",
                img[idx],
                expected[idx],
                err / error_threshold
            ));
        }
    }
    assert!(failures.is_empty(), "{style:?}:\n{}", failures.join("\n"));
}

/// Port of `GenerateIdentityLut3D` (fast red order, 4 channels).
fn generate_identity_lut3d(edge_len: usize) -> Vec<f32> {
    let num_channels = 4;
    let mut img = vec![0.0f32; edge_len * edge_len * edge_len * num_channels];
    let c = 1.0f32 / (edge_len as f32 - 1.0);
    for i in 0..edge_len * edge_len * edge_len {
        img[num_channels * i] = (i % edge_len) as f32 * c;
        img[num_channels * i + 1] = ((i / edge_len) % edge_len) as f32 * c;
        img[num_channels * i + 2] = ((i / edge_len / edge_len) % edge_len) as f32 * c;
    }
    img
}

