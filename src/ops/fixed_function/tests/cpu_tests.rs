// NB: The ACES 2 FixedFunction takes linear ACES2065-1 values and produces
// linear RGB values in the encoding gamut. The relatively large tolerance on
// the following round-trip tests doesn't fully test accuracy of saturated
// values.

fn ot_round_trip(params: &[f64], scale: f32, tolerance: f32) {
    let lut_size = 8;
    let num_samples = lut_size * lut_size * lut_size;
    let mut input_32f = generate_identity_lut3d(lut_size);
    for v in input_32f.iter_mut() {
        *v *= scale;
    }

    let op = renderer(S::AcesOutputTransform20Inv, params);
    let mut px = to_pixels(&input_32f);
    op.apply(&mut px);
    let mut output_32f = vec![0.0f32; input_32f.len()];
    from_pixels(&px, &mut output_32f);

    apply_fixed_function(
        &mut output_32f,
        &input_32f,
        num_samples,
        S::AcesOutputTransform20Fwd,
        params,
        tolerance,
    );
}

